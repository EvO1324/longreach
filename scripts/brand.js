const fs = require('fs');
const path = require('path');
const core = require('./brandCore');

const ROOT = path.join(__dirname, '..');
const rel = p => path.join(ROOT, p);

function readConfig() {
  for (const name of ['va.config.json', 'va.config.example.json']) {
    const file = rel(name);
    if (fs.existsSync(file)) {
      try { return { file: name, data: JSON.parse(fs.readFileSync(file, 'utf8')) }; }
      catch (err) { fail(`${name} isn't valid JSON: ${err.message}`); }
    }
  }
  return { file: '(defaults)', data: {} };
}

function fail(msg) {
  console.error(`\n✖ Brand: ${msg}\n`);
  process.exit(1);
}

function writeIfChanged(file, content) {
  const abs = rel(file);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  if (fs.existsSync(abs) && fs.readFileSync(abs, 'utf8') === content) return;
  fs.writeFileSync(abs, content);
}

function emptyDir(dir) {
  const abs = rel(dir);
  fs.rmSync(abs, { recursive: true, force: true });
  fs.mkdirSync(abs, { recursive: true });
}

function logoSources(config) {
  const pick = (configured, fallback) => {
    if (configured && fs.existsSync(rel(configured))) return configured;
    if (configured) console.warn(`  ! ${configured} not found, using the placeholder`);
    return fallback;
  };
  const icon = pick(config.logos.icon, 'brand/default/icon.svg');
  const sibling = suffix => {
    const p = path.join(path.dirname(icon), suffix);
    return fs.existsSync(rel(p)) ? p : icon;
  };
  return {
    light: pick(config.logos.light, 'brand/default/logo-light.svg'),
    dark: pick(config.logos.dark || config.logos.light, 'brand/default/logo-dark.svg'),
    icon,
    icon192: sibling('icon-192.png'),
    icon512: sibling('icon-512.png'),
    favicon: sibling('favicon.png'),
  };
}

const MIME = { '.png': 'image/png', '.svg': 'image/svg+xml', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp', '.ico': 'image/x-icon' };

function copyLogos(sources, config, colors) {
  emptyDir('public/brand');
  emptyDir('server/assets/brand');
  const publicPaths = {};
  const serverPaths = {};
  for (const [key, src] of Object.entries(sources)) {
    const ext = path.extname(src).toLowerCase();
    const name = { light: 'logo-light', dark: 'logo-dark', icon: 'icon', icon192: 'icon-192', icon512: 'icon-512', favicon: 'favicon' }[key] + ext;
    // no logo of the VA's own yet: draw one from its name and colour
    const placeholder = src.startsWith('brand/default/')
      ? core.placeholderLogo(key === 'light' || key === 'dark' ? key : 'icon', config, colors)
      : null;
    const put = dest => (placeholder ? fs.writeFileSync(rel(dest), placeholder) : fs.copyFileSync(rel(src), rel(dest)));
    put(`public/brand/${name}`);
    publicPaths[key] = `/brand/${name}`;
    if (['light', 'dark', 'icon'].includes(key)) {
      put(`server/assets/brand/${name}`);
      serverPaths[key] = `assets/brand/${name}`;
    }
  }
  return { publicPaths, serverPaths };
}

const esc = s => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

function indexHtml(config, colors, logos) {
  const favType = MIME[path.extname(logos.favicon)] || 'image/png';
  return `<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <!-- Generated by npm run brand from va.config.json -->
    <link rel="icon" type="${favType}" href="%PUBLIC_URL%${logos.favicon}" />
    <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
    <meta name="theme-color" content="${colors.primary}" />
    <meta name="description" content="${esc(`${config.name} ${config.crewCentreName}`)}" />
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />
    <meta name="apple-mobile-web-app-title" content="${esc(config.abbreviation)}" />
    <meta name="mobile-web-app-capable" content="yes" />
    <link rel="apple-touch-icon" href="%PUBLIC_URL%${logos.icon192}" />
    <link rel="manifest" href="%PUBLIC_URL%/manifest.json" />
    <title>${esc(config.crewCentreName)} | ${esc(config.name)}</title>
  </head>
  <body>
    <noscript>You need to enable JavaScript to run this app.</noscript>
    <div id="root"></div>
  </body>
</html>
`;
}

function manifest(config, colors, logos) {
  const icon = (src, sizes) => ({ src: src.replace(/^\//, ''), sizes, type: MIME[path.extname(src)] || 'image/png', purpose: 'any' });
  const svgIcon = path.extname(logos.icon512) === '.svg';
  return JSON.stringify({
    short_name: config.abbreviation,
    name: `${config.shortName} ${config.crewCentreName}`,
    icons: svgIcon
      ? [icon(logos.icon512, 'any')]
      : [icon(logos.icon192, '192x192'), icon(logos.icon512, '512x512')],
    start_url: '.',
    display: 'standalone',
    theme_color: colors.primary,
    background_color: '#ffffff',
  }, null, 2) + '\n';
}

function mapView(config) {
  if (Array.isArray(config.map?.center) && config.map.center.length === 2) {
    return { center: config.map.center, zoom: Number(config.map.zoom) || 4 };
  }
  let airports = [];
  try { airports = JSON.parse(fs.readFileSync(rel('server/airports.json'), 'utf8')); } catch {}
  const byIcao = new Map(airports.map(a => [String(a.icao).toUpperCase(), a]));
  const pts = config.hubs.map(h => byIcao.get(String(h.icao).toUpperCase())).filter(a => a && Number.isFinite(a.lat));
  if (!pts.length) return { center: [20, 0], zoom: 2 };
  const lats = pts.map(a => a.lat), lngs = pts.map(a => a.lng);
  const span = Math.max(Math.max(...lats) - Math.min(...lats), Math.max(...lngs) - Math.min(...lngs));
  const zoom = span < 12 ? 5 : span < 45 ? 4 : span < 90 ? 3 : 2;
  const mid = arr => Math.round(((Math.min(...arr) + Math.max(...arr)) / 2) * 10) / 10;
  return { center: [mid(lats), mid(lngs)], zoom };
}

function main() {
  const { file, data } = readConfig();
  const { config, colors, errors, warnings } = core.resolve(data);
  if (errors.length) fail(`${file} has problems:\n  - ${errors.join('\n  - ')}`);

  const sources = logoSources(config);
  const { publicPaths, serverPaths } = copyLogos(sources, config, colors);
  const cs = core.callsignTools(config.callsign);

  const shared = { ...config, colors: { ...config.colors, ...colors }, callsignRegex: cs.regexSource, map: mapView(config) };
  writeIfChanged('src/brand/config.generated.json', JSON.stringify({ ...shared, logos: publicPaths }, null, 2) + '\n');
  writeIfChanged('server/src/config/brand.generated.json', JSON.stringify({ ...shared, logos: serverPaths, publicLogos: publicPaths }, null, 2) + '\n');
  writeIfChanged('src/brand/brand.css', core.cssFor(colors, config.font));
  const coreSrc = fs.readFileSync(rel('scripts/brandCore.js'), 'utf8');
  const header = '// GENERATED COPY of scripts/brandCore.js (npm run brand). Edit that file instead.\n';
  writeIfChanged('src/brand/brandCore.js', header + coreSrc);
  writeIfChanged('server/src/config/brandCore.js', header + coreSrc);
  writeIfChanged('public/index.html', indexHtml(config, colors, publicPaths));
  writeIfChanged('public/manifest.json', manifest(config, colors, publicPaths));
  writeIfChanged('public/service-worker.js', fs.readFileSync(rel('scripts/templates/service-worker.js'), 'utf8')
    .replace(/^const APP_ICON = .*$/m, `const APP_ICON = '${publicPaths.icon192}';`));

  console.log(`✓ Brand: ${config.name} (${file}) · ${cs.format(cs.min)} · ${colors.primary} / ${colors.accent}`);
  for (const w of warnings) console.log(`  ! ${w}`);
}

if (require.main === module) main();
module.exports = { main };
